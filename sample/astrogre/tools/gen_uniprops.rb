#!/usr/bin/env ruby
# Generates src/uniprops.rs from CRuby's enc/unicode/<ver>/name2ctype.h (the Onigmo property tables).
#   ruby tools/gen_uniprops.rb ~/ruby/src/ruby_4_0/enc/unicode/17.0.0/name2ctype.h > src/uniprops.rs
# Output is plain arrays (no pointers), so the data needs no load-time relocation.
raw = File.read(ARGV[0] || abort("usage: gen_uniprops.rb name2ctype.h"))
# Evaluate #ifdef/#ifndef/#else/#endif for the macros CRuby defines (regenc.h).
DEFINED = %w[USE_UNICODE_PROPERTIES USE_UNICODE_AGE_PROPERTIES]
stack = []
src = +""
raw.each_line do |l|
  case l
  when /^#\s*ifdef (\w+)/ then stack << DEFINED.include?($1)
  when /^#\s*ifndef (\w+)/ then stack << !DEFINED.include?($1)
  when /^#\s*else/ then stack[-1] = !stack[-1]
  when /^#\s*endif/ then stack.pop
  else src << l if stack.all?
  end
end
ver = src[/ONIG_UNICODE_VERSION_STRING "([\d.]+)"/, 1]

arrays = {}   # CR_name => [lo, hi, ...]
src.scan(/^static const OnigCodePoint (CR_\w+)\[\] = \{\n\t(\d+),\n(.*?)^\};/m) do |name, n, body|
  v = body.scan(/0x[0-9a-fA-F]+/).map { |x| x.hex }
  raise "len #{name}" unless v.size == n.to_i * 2
  arrays[name] = v
end
src.scan(/^#define (CR_\w+) (CR_\w+)$/) { |a, b| arrays[a] = arrays.fetch(b) }

code_ranges = src[/CodeRanges\[\] = \{\n(.*?)^\};/m, 1].scan(/CR_\w+/)

# name pool: strN => name, only inside the USE_UNICODE_PROPERTIES branch of the struct
decl = src[/^struct uniname2ctype_pool_t\n\s*\{\n(.*?)^\s*\};/m, 1]
uni = decl
str2name = {}
uni.scan(/uniname2ctype_pool_str(\d+)\[sizeof\("([^"]*)"\)\]/) { |n, s| str2name[n] = s }
wl = src[/wordlist\[\] =\s*\{\n(.*?)^\s*\};/m, 1]
names = {}
wl.scan(/uniname2ctype_offset\(str(\d+)\), (\d+)\}/) { |n, k| names[str2name.fetch(n)] = code_ranges.fetch(k.to_i) }
raise "few names #{names.size}" unless names.size == src[/define TOTAL_KEYWORDS (\d+)/, 1].to_i

uniq = {} # content => id
ids = []
names.keys.sort.each { |n| ids << (uniq[arrays.fetch(names[n])] ||= uniq.size) }
std = code_ranges.first(16).map { |c| uniq[arrays.fetch(c)] ||= uniq.size }
named = ->(n) { uniq[arrays.fetch(names.fetch(n))] }
flat = []
offs = [0]
uniq.keys.each { |v| flat.concat(v); offs << flat.size / 2 }
sorted = names.keys.sort
blob = +""
noff = [0]
sorted.each { |n| blob << n; noff << blob.size }

def arr(name, ty, vals, per = 12, fmt = "%d")
  s = +"pub static #{name}: [#{ty}; #{vals.size}] = [\n"
  vals.each_slice(per) { |sl| s << "    " << sl.map { |x| fmt % x }.join(", ") << ",\n" }
  s << "];\n"
end

puts "// Generated by tools/gen_uniprops.rb from CRuby's name2ctype.h (Unicode #{ver}). Do not edit."
puts "// Each property is a sorted [lo, hi, lo, hi, ...] range list inside UP_RANGES; UP_OFF[id]..UP_OFF[id+1] are its pairs (in pairs)."
puts "pub const UNICODE_VERSION: &str = \"#{ver}\";"
puts "pub const UP_COUNT: usize = #{uniq.size};"
%w[NEWLINE ALPHA BLANK CNTRL DIGIT GRAPH LOWER PRINT XPUNCT SPACE UPPER XDIGIT WORD ALNUM ASCII PUNCT].each_with_index do |n, i|
  puts "pub const UP_#{n}: u16 = #{std[i]};"
end
%w[control cr extend l lf lv lvt prepend regionalindicator spacingmark t v zwj].each { |n| puts "pub const UP_GCB_#{n.upcase}: u16 = #{named.("graphemeclusterbreak=#{n}")};" }
%w[consonant extend linker].each { |n| puts "pub const UP_INCB_#{n.upcase}: u16 = #{named.("incb=#{n}")};" }
puts "pub const UP_EXTPICT: u16 = #{named.("extendedpictographic")};"
puts arr("UP_NAME_BLOB", "u8", blob.bytes, 24)
puts arr("UP_NAME_OFF", "u32", noff, 16)
puts arr("UP_NAME_ID", "u16", ids, 24)
puts arr("UP_OFF", "u32", offs, 16)
puts arr("UP_RANGES", "u32", flat, 8, "0x%x")
File.write(ENV["NAMES_OUT"], sorted.join("\n") + "\n") if ENV["NAMES_OUT"]

# Simple (1 code point) case-equivalence classes from casefold.h: CaseFold_11 (x -> fold) and
# CaseUnfold_11 (fold -> x...), plus siblings listed together in CaseUnfold_12/13 (e.g. U+DF and U+1E9E).
cf = File.read(File.join(File.dirname(ARGV[0]), "casefold.h"))
fold_part = cf[/CaseFold_11_Table\[\] = \{\n(.*?)^\};/m, 1].split(/^#define CaseFold_Locale.*\n/, 2)[0]
unf_part = cf[/CaseUnfold_11_Table\[\] = \{\n(.*?)^\};/m, 1]
parent = Hash.new { |h, k| h[k] = k }
find = ->(x) { parent[x] == x ? x : (parent[x] = find.(parent[x])) }
fold_part.scan(/\{(0x\h+), \{1\|[\w|]*, \{(0x\h+)\}\}\}/) { |a, b| parent[find.(a.hex)] = find.(b.hex) }
unf_part.scan(/\{(0x\h+), \{(\d+)\|[\w|]*, \{([^}]*)\}\}\}/) do |a, n, l|
  l.scan(/0x\h+/).each { |x| parent[find.(x.hex)] = find.(a.hex) }
end
%w[12 13].each do |k|
  cf[/CaseUnfold_#{k}_Table\[\] = \{\n(.*?)^\};/m, 1].scan(/\{\{[^}]*\}, \{\d+, \{([^}]*)\}\}\}/) do |l|
    m = l[0].scan(/0x\h+/).map(&:hex)
    m.each_cons(2) { |a, b| parent[find.(b)] = find.(a) }
  end
end
groups = parent.keys.group_by { |k| find.(k) }.values.map(&:sort).select { |g| g.size > 1 }.sort
cf_codes = []
cf_cls = []
cf_members = []
cf_off = [0]
groups.each_with_index do |g, i|
  g.each { |x| cf_codes << x; cf_cls << i }
  cf_members.concat(g)
  cf_off << cf_members.size
end
order = (0...cf_codes.size).sort_by { |i| cf_codes[i] }
puts "// Case-equivalence classes (single code point folds): CF_CODE (sorted) -> CF_CLS -> CF_MEMBERS[CF_OFF[c]..CF_OFF[c+1]]."
puts arr("CF_CODE", "u32", order.map { |i| cf_codes[i] }, 8, "0x%x")
puts arr("CF_CLS", "u16", order.map { |i| cf_cls[i] }, 24)
puts arr("CF_OFF", "u32", cf_off, 16)
puts arr("CF_MEMBERS", "u32", cf_members, 8, "0x%x")
