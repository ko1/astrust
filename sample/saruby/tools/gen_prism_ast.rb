# Generates src/prism_ast.rs: Rust types for prism's AST and a deserializer for
# pm_serialize_parse's byte format.  The node list and field order come from the
# vendored prism's config.yml through its own template loader, so the reader stays
# in step with the C serializer of the same revision.
require_relative '../vendor/prism/templates/template'

T = Prism::Template
L = T.send(:locals)
nodes = L[:nodes]
flags = L[:flags]

RUST_KW = %w[as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try]
def fname(n) = RUST_KW.include?(n) ? "r##{n}" : n

def ftype(f)
  case f
  when T::NodeField then 'Box<Node>'
  when T::OptionalNodeField then 'Option<Box<Node>>'
  when T::NodeListField then 'Vec<Node>'
  when T::StringField then 'Vec<u8>'
  when T::ConstantField then 'Cst'
  when T::OptionalConstantField then 'Option<Cst>'
  when T::ConstantListField then 'Vec<Cst>'
  when T::LocationField then 'Loc'
  when T::OptionalLocationField then 'Option<Loc>'
  when T::UInt8Field then 'u8'
  when T::UInt32Field then 'u32'
  when T::IntegerField then 'PInt'
  when T::DoubleField then 'f64'
  else raise f.inspect
  end
end

def freader(f)
  case f
  when T::NodeField then 'Box::new(r.node())'
  when T::OptionalNodeField then 'r.opt_node()'
  when T::NodeListField then '{ let k = r.varu(); (0..k).map(|_| r.node()).collect() }'
  when T::StringField then 'r.string()'
  when T::ConstantField then 'r.varu() - 1'
  when T::OptionalConstantField then '{ let k = r.varu(); if k == 0 { None } else { Some(k - 1) } }'
  when T::ConstantListField then '{ let k = r.varu(); (0..k).map(|_| r.varu() - 1).collect() }'
  when T::LocationField then 'r.loc()'
  when T::OptionalLocationField then 'r.opt_loc()'
  when T::UInt8Field then 'r.byte()'
  when T::UInt32Field then 'r.varu()'
  when T::IntegerField then 'r.integer()'
  when T::DoubleField then 'r.double()'
  end
end

out = +<<~RS
  // Auto-generated by tools/gen_prism_ast.rb from vendor/prism/config.yml. Do not edit.
  #![allow(dead_code, non_camel_case_types, clippy::all)]
  use super::prism::{Reader, Loc, PInt, Cst};
  use super::prism_generic::*;

  #[derive(Debug)]
  pub struct Node { pub id: u32, pub loc: Loc, pub flags: u32, pub kind: Kind }

  #[derive(Debug)]
  pub enum Kind {
RS
LOCF = [T::LocationField, T::OptionalLocationField]
# locations the compiler reads (a call's line is its message's, as CRuby's)
# locations the compiler reads, as their start offset `x_start` (u32::MAX: none; a Loc would grow the node):
# a call's line is its message's, as CRuby's
KEEP_LOC = { 'CallNode' => ['message_loc'] }
def loc_kept?(n, f) = KEEP_LOC.fetch(n.name, []).include?(f.name)
def kname(n, f) = loc_kept?(n, f) ? f.name.sub(/_loc\z/, '_start') : fname(f.name)
def ktype(n, f) = loc_kept?(n, f) ? 'u32' : ftype(f)
def kreader(n, f) = loc_kept?(n, f) ? (f.is_a?(T::OptionalLocationField) ? 'r.opt_loc().map_or(u32::MAX, |l| l.start)' : 'r.loc().start') : freader(f)
def kept(n) = n.fields.select(&:should_be_serialized?).reject { LOCF.include?(it.class) && !loc_kept?(n, it) }
nodes.each do |n|
  fs = kept(n)
  if fs.empty?
    out << "    #{n.name},\n"
  else
    out << "    #{n.name} { #{fs.map { "#{kname(n, it)}: #{ktype(n, it)}" }.join(', ')} },\n"
  end
end
out << "}\n\n"

flags.each do |fl|
  fl.values.each_with_index do |v, i|
    out << "pub const #{fl.human.upcase}_#{v.name}: u32 = 1 << #{i + T::COMMON_FLAGS_COUNT};\n"
  end
end
out << "pub const FLAG_NEWLINE: u32 = 1;\npub const FLAG_STATIC_LITERAL: u32 = 2;\n\n"

out << "impl<'a> Reader<'a> {\n    pub fn node(&mut self) -> Node {\n        let r = self;\n        let ty = r.byte();\n        let id = r.varu();\n        let loc = r.loc();\n        match ty {\n"
nodes.each.with_index(1) do |n, i|
  all = n.fields.select(&:should_be_serialized?)
  fs = kept(n)
  pre = n.needs_serialized_length? ? "r.skip(4); " : ""
  if all.empty?
    out << "            #{i} => { #{pre}let flags = r.varu(); Node { id, loc, flags, kind: Kind::#{n.name} } }\n"
  else
    out << "            #{i} => { #{pre}let flags = r.varu();\n"
    all.each { out << (LOCF.include?(it.class) && !loc_kept?(n, it) ? "                let _ = #{freader(it)};\n" : "                let #{kname(n, it)} = #{kreader(n, it)};\n") }
    out << "                Node { id, loc, flags, kind: Kind::#{n.name} { #{fs.map { kname(n, it) }.join(', ')} } } }\n"
  end
end
out << "            _ => panic!(\"prism: unknown node type {}\", ty),\n        }\n    }\n}\n\n"

out << "pub fn kind_name(k: &Kind) -> &'static str {\n    match k {\n"
nodes.each do |n|
  fs = kept(n)
  out << "        Kind::#{n.name}#{fs.empty? ? '' : ' { .. }'} => \"#{n.name}\",\n"
end
out << "    }\n}\n"

out << "\nimpl Node {\n    /// Direct child nodes, in field order.\n    pub fn children(&self) -> Vec<&Node> {\n        let mut v: Vec<&Node> = vec![];\n        match &self.kind {\n"
nodes.each do |n|
  fs = kept(n)
  nf = fs.select { [T::NodeField, T::OptionalNodeField, T::NodeListField].include?(it.class) }
  if nf.empty?
    out << "            Kind::#{n.name}#{fs.empty? ? '' : ' { .. }'} => {}\n"
  else
    out << "            Kind::#{n.name} { #{nf.map { fname(it.name) }.join(', ')}, .. } => {\n"
    nf.each do |f|
      case f
      when T::NodeField then out << "                v.push(#{fname(f.name)});\n"
      when T::OptionalNodeField then out << "                if let Some(x) = #{fname(f.name)} { v.push(x); }\n"
      when T::NodeListField then out << "                for x in #{fname(f.name)} { v.push(x); }\n"
      end
    end
    out << "            }\n"
  end
end
out << "        }\n        v\n    }\n}\n"

# every field of every node, in serialization order: prism_generic.rs reads a whole node from it (error_highlight)
FCODE = { T::NodeField => 'F_NODE', T::OptionalNodeField => 'F_OPT_NODE', T::NodeListField => 'F_NODES', T::StringField => 'F_STR',
  T::ConstantField => 'F_CST', T::OptionalConstantField => 'F_OPT_CST', T::ConstantListField => 'F_CSTS', T::LocationField => 'F_LOC',
  T::OptionalLocationField => 'F_OPT_LOC', T::UInt8Field => 'F_U8', T::UInt32Field => 'F_U32', T::IntegerField => 'F_INT', T::DoubleField => 'F_F64' }
out << "\n/// (type, serialized length prefix, fields) by node type - 1\npub static SCHEMA: &[(&str, bool, &[(&str, u8)])] = &[\n"
nodes.each do |n|
  fs = n.fields.select(&:should_be_serialized?).map { "(\"#{it.name}\", #{FCODE.fetch(it.class)})" }
  out << "    (\"#{n.human}\", #{n.needs_serialized_length?}, &[#{fs.join(', ')}]),\n"
end
out << "];\n"
# token type names by type - 1 (pm_serialize_lex's ids; syntax_suggest's lexer, builtins/syntax_suggest.rs)
out << "\n/// token type names by type - 1\npub static TOKEN_NAMES: &[&str] = &[\n"
L[:tokens].each { out << "    \"#{it.name}\",\n" }
out << "];\n"
File.write(File.expand_path('../src/prism_ast.rs', __dir__), out)

