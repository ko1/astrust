# Generates src/builtins/socket_consts.rs (Socket::Constants) for src/builtins/socket.rs.
#   ruby tools/gen_socket_consts.rb ~/ruby/src/ruby_4_0 > src/builtins/socket_consts.rs
# Names come in the order of ext/socket/mkconstants.rb's table (that order decides which name
# CRuby shows for a value shared by several constants); values and the set of names are the
# running CRuby's, i.e. this platform's. One string and one integer array: no load-time relocations.
require 'socket'

SRC = File.expand_path(ARGV[0] || '~/ruby/src/ruby_4_0')
data = File.read("#{SRC}/ext/socket/mkconstants.rb").split(/^__END__\n/, 2)[1]
names = data.each_line.map { |l| l.split(/\s+/, 2)[0] }.reject { |n| n.nil? || n.empty? || n.start_with?('#') }.uniq
defined = Socket::Constants.constants.map(&:to_s)
missing = defined - names
abort "not in mkconstants.rb: #{missing.join(' ')}" unless missing.empty?
names = names.select { |n| defined.include?(n) }
puts "#![forbid(unsafe_code)]"
puts "// Generated by tools/gen_socket_consts.rb from CRuby #{RUBY_VERSION} (#{RUBY_PLATFORM}); do not edit."
puts "// Names (space-separated) and values, in mkconstants.rb order."
puts "pub const NAMES: &str = concat!("
names.each_slice(8) { |sl| puts "    #{(sl.join(' ') + ' ').dump}," }
puts ").trim_ascii_end();"
puts "pub const VALUES: [i64; #{names.size}] = ["
names.each_slice(8) { |sl| puts "    " + sl.map { |n| Socket::Constants.const_get(n).to_s }.join(", ") + "," }
puts "];"
