# Generates src/builtins/enc_tables.rs from CRuby's transcoders (the oracle).
#   ruby tools/gen_enc_tables.rb > src/builtins/enc_tables.rs
SINGLE = Encoding.list.select { |e|
  e.ascii_compatible? && !e.dummy? &&
    (e.name =~ /\A(ISO-8859|Windows-12|KOI8|IBM|CP8|mac|TIS|Windows-874)/i)
}.map(&:name)

def u(bytes, enc)
  bytes.force_encoding(enc).encode('UTF-8').ord
rescue EncodingError
  0
end

def words(a) = a.each_slice(16).map { |s| "    " + s.map { |x| "0x%x," % x }.join }.join("\n")

puts "// Generated by tools/gen_enc_tables.rb from CRuby #{RUBY_VERSION}; do not edit."
puts "// Byte -> Unicode tables (0 = undefined)."
puts "#![forbid(unsafe_code)]"
puts "pub const SINGLE_NAMES: [&str; #{SINGLE.size}] = [#{SINGLE.map(&:inspect).join(', ')}];"
puts "pub static SINGLE: [[u16; 128]; #{SINGLE.size}] = ["
SINGLE.each do |n|
  puts "  [", words((0x80..0xff).map { |b| u(b.chr, n) }), "  ],"
end
puts "];"

# EUC-JP: JIS X 0208 (A1-FE x A1-FE) and JIS X 0212 (8F + A1-FE x A1-FE).
%w[EUC-JP CP51932].each_with_index do |enc, k|
  t = []
  (0xa1..0xfe).each { |h| (0xa1..0xfe).each { |l| t << u([h, l].pack('C*'), enc) } }
  puts "pub static #{k == 0 ? 'EUCJP' : 'CP51932'}: [u16; #{t.size}] = [", words(t), "];"
end
t = []
(0xa1..0xfe).each { |h| (0xa1..0xfe).each { |l| t << u([0x8f, h, l].pack('C*'), 'EUC-JP') } }
puts "pub static EUCJP_0212: [u16; #{t.size}] = [", words(t), "];"

# Shift_JIS / Windows-31J: lead 81-9F,E0-FC x trail 40-FC.
LEADS = (0x81..0x9f).to_a + (0xe0..0xfc).to_a
%w[Shift_JIS Windows-31J].each do |enc|
  t = []
  LEADS.each { |h| (0x40..0xfc).each { |l| t << u([h, l].pack('C*'), enc) } }
  puts "pub static #{enc == 'Shift_JIS' ? 'SJIS' : 'CP932'}: [u16; #{t.size}] = [", words(t), "];"
end

# rb_enc_isprint of the single high bytes (0x80-0xFF) per encoding, as bitmaps; encodings with none are left out.
# ([[:print:]] in an ASCII-only regexp takes the subject's encoding, as rb_enc_isprint does.)
pr = Encoding.list.select { |e| e.ascii_compatible? && !e.dummy? }.filter_map do |e|
  bits = (0x80..0xff).select { |b| s = b.chr.force_encoding(e); s.valid_encoding? && /\A[[:print:]]\z/.match?(s) }
  next if bits.empty?
  m = Array.new(16, 0); bits.each { |b| m[(b - 0x80) >> 3] |= 1 << (b & 7) }
  [e.name, m]
end
puts "pub const PRINT_HI: [(&str, [u8; 16]); #{pr.size}] = ["
pr.each { |n, m| puts "  (#{n.inspect}, [#{m.map { "0x%02x" % _1 }.join(', ')}])," }
puts "];"
