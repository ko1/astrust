# Generates src/builtins/trans_tables.rs (CRuby's transcoder tables, enc/trans/*.c) for
# src/builtins/econv.rs.
#   ruby tools/gen_trans_tables.rb ~/ruby/src/ruby_4_0 > src/builtins/trans_tables.rs
# Needs a configured CRuby tree (the generated enc/trans/*.c, transdb.h, .ext/include). Each
# table file is compiled into a small C program that registers its transcoders and prints
# them, so the arrays and the transcoder fields come out exactly as CRuby has them.
require 'tmpdir'

SRC = File.expand_path(ARGV[0] || '~/ruby/src/ruby_4_0')  # the 4.0 branch: some max_output differ on master
TRANS = "#{SRC}/enc/trans"
ARCH_INC = Dir["#{SRC}/.ext/include/*"].find { |d| File.exist?("#{d}/ruby/config.h") } or abort "no #{SRC}/.ext/include/<arch>"
FILES = Dir["#{TRANS}/*.c"].map { |f| File.basename(f, '.c') }.reject { |n| n == 'transdb' }.sort
FIELDS = %w[state_init_func state_fini_func func_ii func_si func_io func_so finish_func resetsize_func resetstate_func func_sio]

def camel(s) = s.split('_').map(&:capitalize).join

def run_file(name)
  src = File.read("#{TRANS}/#{name}.c")
  body = src[/^#define TRANSCODE_TABLE_INFO.*/m] || ''
  funcs = body.scan(/^([a-z_][a-z0-9_]*)\s*\(/).flatten.uniq - %w[TRANS_INIT]
  code = body.gsub(/^static const rb_transcoder\n.*?^\};/m, '')
  consts = src.scan(/^#define (\w+) WORDINDEX2INFO/).flatten.select { |d| code =~ /\b#{d}\b/ }
  init = src =~ /TRANS_INIT\((\w+)\)/ ? "Init_#{$1}" : (src[/^(Init_\w+)\s*\(/, 1] or abort name)
  c = +<<~C
    #include <stdio.h>
    #include "#{TRANS}/#{name}.c"
    static void pr(const char *k, const void *p) {
    C
  funcs.each { |f| c << %Q{  if (p == (const void *)#{f}) { printf(" %s=#{f}", k); return; }\n} }
  c << <<~C
      if (p) { printf(" %s=?", k); return; }
    }
    void rb_register_transcoder(const rb_transcoder *t) {
      printf("TR\\t%s\\t%s\\t%u\\t%d\\t%d\\t%d\\t%d\\t%d", t->src_encoding, t->dst_encoding, t->conv_tree_start,
             t->input_unit_length, t->max_input, t->max_output, (int)t->asciicompat_type, (int)t->state_size);
      #{FIELDS.map { |f| %Q{pr("#{f}", (const void *)t->#{f});} }.join("\n  ")}
      printf("\\n");
    }
    void rb_declare_transcoder(const char *a, const char *b, const char *c) {}
    int main(void) {
      unsigned i;
      printf("BYTES");
      for (i = 0; i < sizeof(#{name}_byte_array); i++) printf(" %u", #{name}_byte_array[i]);
      printf("\\nWORDS");
      for (i = 0; i < sizeof(#{name}_word_array) / sizeof(unsigned int); i++) printf(" %u", #{name}_word_array[i]);
      printf("\\n");
      #{consts.map { |k| %Q{printf("CONST\\t#{k}\\t%u\\n", (unsigned)(#{k}));} }.join("\n  ")}
      #{init}();
      return 0;
    }
  C
  Dir.mktmpdir do |d|
    File.write("#{d}/h.c", c)
    system('cc', '-w', '-O0', "-I#{SRC}/include", "-I#{ARCH_INC}", "-I#{SRC}", '-o', "#{d}/h", "#{d}/h.c") or abort "cc #{name}"
    IO.popen("#{d}/h", &:read)
  end
end

def lit(bytes)
  s = +'b"'
  bytes.each do |b|
    s << case b
         when 0x5c then '\\\\'
         when 0x22 then '\\"'
         when 0x20..0x7e then b.chr
         when 0 then '\\0'
         else format('\\x%02x', b)
         end
  end
  s << '"'
end

files = []
trs = []
consts = {}
fns = ['None']
FILES.each_with_index do |name, fi|
  out = run_file(name)
  bytes = out[/^BYTES(.*)$/, 1].split.map(&:to_i)
  words = out[/^WORDS(.*)$/, 1].split.map(&:to_i)
  files << [name, bytes, words]
  out.scan(/^CONST\t(\w+)\t(\d+)$/) { |k, v| consts[k.upcase] = v.to_i }
  out.each_line.grep(/^TR\t/).each do |l|
    f = l.chomp.split("\t")
    ss, *kvs = f[8].split
    h = kvs.to_h { |kv| kv.split('=') }
    abort "unknown function in #{name}: #{l}" if h.value?('?')
    h.each_value { |v| fns << camel(v) unless fns.include?(camel(v)) }
    trs << [f[1], f[2], fi, *f[3..7].map(&:to_i), ss.to_i, h]
  end
end

decls = File.read("#{SRC}/transdb.h").scan(/rb_declare_transcoder\("([^"]*)", "([^"]*)", "([^"]*)"\)/)

rev = (File.read("#{SRC}/revision.h")[/RUBY_FULL_REVISION "(\w+)"/, 1] rescue '?')
puts "// Generated by tools/gen_trans_tables.rb from CRuby #{rev} (enc/trans/*.c, transdb.h); do not edit."
puts "// `words` are CRuby's word arrays as little-endian u32s."
puts '#![forbid(unsafe_code)]'
puts '#![allow(dead_code)]'
puts 'pub struct TrFile { pub name: &\'static str, pub bytes: &\'static [u8], pub words: &\'static [u8] }'
puts "pub static FILES: [TrFile; #{files.size}] = ["
files.each do |n, b, w|
  puts "  TrFile { name: #{n.inspect}, bytes: #{lit(b)},"
  puts "    words: #{lit(w.pack('V*').bytes)} },"
end
puts '];'
puts '#[derive(Clone, Copy, PartialEq, Eq, Debug)]'
puts "pub enum TrFn { #{fns.join(', ')} }"
puts '/// asciicompat: 0 converter, 1 decoder, 2 encoder (rb_transcoder_asciicompat_type_t).'
puts 'pub struct TrDef {'
puts '    pub src: &\'static str, pub dst: &\'static str, pub file: u8, pub tree_start: u32,'
puts '    pub unit_len: u8, pub max_in: u8, pub max_out: u8, pub asciicompat: u8, pub state_size: u8,'
puts "    #{FIELDS.map { |f| "pub #{f}: TrFn" }.join(', ')},"
puts '}'
puts "pub static TRANSCODERS: [TrDef; #{trs.size}] = ["
trs.each do |s, d, fi, ts, ul, mi, mo, ac, ss, h|
  fl = FIELDS.map { |f| "#{f}: TrFn::#{h[f] ? camel(h[f]) : 'None'}" }.join(', ')
  puts "  TrDef { src: #{s.inspect}, dst: #{d.inspect}, file: #{fi}, tree_start: #{ts}, unit_len: #{ul}, max_in: #{mi}, max_out: #{mo}, asciicompat: #{ac}, state_size: #{ss}, #{fl} },"
end
puts '];'
puts '/// transdb.h: (source, destination, library) in declaration order (the search order).'
puts "pub static DECLS: [(&str, &str, &str); #{decls.size}] = ["
decls.each { |a, b, c| puts "  (#{a.inspect}, #{b.inspect}, #{c.inspect})," }
puts '];'
consts.sort.each { |k, v| puts "pub const #{k}: u32 = #{v};" }
