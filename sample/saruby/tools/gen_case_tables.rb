# Generates src/builtins/case_tables.rs from CRuby (the oracle): the code points whose
# capitalize / swapcase / downcase(:fold) differ from the default rule string.rs applies
# (title = upcase, swap = Uppercase ? downcase : upcase, fold = downcase; Rust's char mappings
# agree with CRuby's upcase/downcase for every single code point).
#   ruby tools/gen_case_tables.rb > src/builtins/case_tables.rs
title = []; swap = []; fold = []
(0..0x10FFFF).each do |cp|
  next if (0xD800..0xDFFF).cover?(cp)
  s = cp.chr(Encoding::UTF_8)
  u = s.upcase; d = s.downcase
  title << [cp, s.capitalize] if s.capitalize != u
  sw = s.match?(/\p{Uppercase}/) ? d : u
  swap << [cp, s.swapcase] if s.swapcase != sw
  fold << [cp, s.downcase(:fold)] if s.downcase(:fold) != d
end
def tab(name, a)
  "pub static #{name}: [(u32, &str); #{a.size}] = [\n" +
    a.map { |cp, s| "    (0x%x, \"%s\")," % [cp, s.each_char.map { |ch| ch.ord < 0x80 ? ch : "\\u{%x}" % ch.ord }.join] }.join("\n") + "\n];"
end
puts "// Generated by tools/gen_case_tables.rb from CRuby #{RUBY_VERSION}; do not edit."
puts "// Exceptions to the default per-character case rules (sorted by code point)."
puts "#![forbid(unsafe_code)]"
puts tab("TITLE", title), tab("SWAP", swap), tab("FOLD", fold)
